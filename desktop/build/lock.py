"""Resolve desktop/requirements-desktop.txt into desktop/runtime.lock: exact versions and SHA-256
hashes of the Windows x64 / Python 3.12 wheels, so every user's PC installs the very files you
tested. Run with the same Python as the app (py -3.12), on Windows.

    py -3.12 desktop/build/lock.py [--tensorrt]

--tensorrt adds NVIDIA TensorRT 10 (from pypi.nvidia.com) for the TensorRT FP16 engines.
"""
import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REQ = ROOT / "desktop" / "requirements-desktop.txt"
LOCK = ROOT / "desktop" / "runtime.lock"
NVIDIA = "https://pypi.nvidia.com"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tensorrt", action="store_true")
    a = ap.parse_args()
    if sys.version_info[:2] != (3, 12) or sys.platform != "win32":
        sys.exit("Run this with Python 3.12 on Windows (py -3.12), the Python the app ships with.")
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        cmd = [sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--only-binary=:all:",
               "--disable-pip-version-check", "--quiet", "--report", str(report), "-r", str(REQ)]
        if a.tensorrt:
            cmd += ["--extra-index-url", NVIDIA, "tensorrt-cu12-libs>=10,<11"]
        subprocess.run(cmd, check=True)
        items = json.loads(report.read_text(encoding="utf-8"))["install"]
    lines = ["# Generated by desktop/build/lock.py from requirements-desktop.txt. Don't edit by hand.",
             "# Python 3.12, Windows x64 wheels. Changing this file makes every PC reinstall its GPU runtime."]
    if a.tensorrt:
        lines.append(f"--extra-index-url {NVIDIA}")
    pins = []
    for it in items:
        md, info = it["metadata"], it.get("download_info", {}).get("archive_info", {})
        sha = (info.get("hashes") or {}).get("sha256") or (info.get("hash", "").split("=", 1)[1] if "=" in info.get("hash", "") else "")
        if not sha:
            sys.exit(f"pip gave no hash for {md['name']}")
        pins.append(f"{md['name'].lower()}=={md['version']} --hash=sha256:{sha}")
    LOCK.write_text("\n".join(lines + sorted(pins)) + "\n", encoding="utf-8")
    print(f"{LOCK.relative_to(ROOT)}: {len(pins)} packages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
